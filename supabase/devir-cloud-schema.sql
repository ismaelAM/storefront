create or replace function public.devir_sync_acquire_lock(p_seconds integer default 55)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_acquired boolean := false;
begin
  update public.devir_sync_config
  set lock_until = now() + make_interval(secs => greatest(10, least(p_seconds, 240))),
      last_attempt_at = now(),
      updated_at = now()
  where id = 'primary'
    and (lock_until is null or lock_until < now())
  returning true into v_acquired;

  return coalesce(v_acquired, false);
end;
$$;

create or replace function public.devir_sync_release_lock()
returns void
language sql
security definer
set search_path = ''
as $$
  update public.devir_sync_config
  set lock_until = null, updated_at = now()
  where id = 'primary';
$$;

revoke all on function public.devir_sync_acquire_lock(integer) from public, anon, authenticated;
revoke all on function public.devir_sync_release_lock() from public, anon, authenticated;
grant execute on function public.devir_sync_acquire_lock(integer) to service_role;
grant execute on function public.devir_sync_release_lock() to service_role;

do $$
declare
  v_token text;
begin
  select decrypted_secret
  into v_token
  from vault.decrypted_secrets
  where name = 'devir_sync_worker_token'
  limit 1;

  if v_token is null then
    v_token := encode(extensions.gen_random_bytes(32), 'hex');
    perform vault.create_secret(
      v_token,
      'devir_sync_worker_token',
      'Bearer token used only by Supabase Cron to invoke the Devir sync worker',
      null
    );
  end if;

  insert into public.devir_sync_config (
    id, worker_token_hash, worker_url, enabled, next_due_at
  )
  values (
    'primary',
    encode(extensions.digest(v_token, 'sha256'), 'hex'),
    'https://ikglqbjlbkbaronbiryl.supabase.co/functions/v1/devir-sync',
    false,
    now()
  )
  on conflict (id) do update
  set worker_token_hash = excluded.worker_token_hash,
      worker_url = excluded.worker_url,
      updated_at = now();
end;
$$;

select cron.unschedule(jobid)
from cron.job
where jobname = 'devir-cloud-sync-tick';

select cron.schedule(
  'devir-cloud-sync-tick',
  '* * * * *',
  $cron$
  select net.http_post(
    url := (select worker_url from public.devir_sync_config where id = 'primary'),
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'x-devir-worker-token',
      (select decrypted_secret from vault.decrypted_secrets where name = 'devir_sync_worker_token' limit 1)
    ),
    body := jsonb_build_object('source', 'supabase-cron', 'at', now()),
    timeout_milliseconds := 120000
  );
  $cron$
);
