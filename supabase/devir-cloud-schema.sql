-- Devir cloud sync infrastructure for BisonTCG.
-- Idempotent reference/bootstrap SQL. Contains no credentials.
-- Runtime secrets (worker token, Spree key, Devir session) are injected separately.

create extension if not exists pg_cron with schema pg_catalog;
create extension if not exists pg_net;

create table if not exists public.devir_sync_config (
  id text primary key,
  enabled boolean not null default false,
  base_url text not null default 'https://b2bdevir.es',
  spree_api_url text not null default 'https://bisontcg.spree.sh',
  spree_admin_api_key text,
  session_state jsonb,
  worker_url text not null default 'https://ikglqbjlbkbaronbiryl.supabase.co/functions/v1/devir-sync',
  worker_token_hash text,
  interval_hours integer not null default 6 check (interval_hours between 1 and 168),
  batch_size integer not null default 4 check (batch_size between 1 and 20),
  max_pages integer not null default 200 check (max_pages between 1 and 500),
  phase text not null default 'idle' check (phase in ('idle','categories','products','error')),
  active_cycle_id uuid,
  next_due_at timestamptz not null default now(),
  lock_until timestamptz,
  last_attempt_at timestamptz,
  last_success_at timestamptz,
  last_error text,
  updated_at timestamptz not null default now()
);

create table if not exists public.devir_sync_cycles (
  id uuid primary key default gen_random_uuid(),
  status text not null default 'running' check (status in ('running','success','error')),
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  category_count integer not null default 0,
  product_count integer not null default 0,
  processed_count integer not null default 0,
  error_count integer not null default 0,
  stats jsonb not null default '{}'::jsonb,
  error text
);

create table if not exists public.devir_sync_jobs (
  id bigint generated by default as identity primary key,
  cycle_id uuid not null references public.devir_sync_cycles(id) on delete cascade,
  kind text not null check (kind in ('category','product')),
  url text not null,
  page integer not null default 1 check (page > 0),
  status text not null default 'pending' check (status in ('pending','processing','done','error')),
  attempts integer not null default 0,
  payload jsonb not null default '{}'::jsonb,
  error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (cycle_id, kind, url, page)
);

create index if not exists devir_sync_jobs_cycle_status_idx
  on public.devir_sync_jobs (cycle_id, kind, status, id);

create table if not exists public.devir_sync_catalog (
  supplier_sku text primary key,
  source_url text not null,
  name text not null,
  snapshot jsonb not null,
  image_urls jsonb not null default '[]'::jsonb,
  image_signature text,
  spree_product_id text,
  spree_variant_id text,
  images_managed boolean not null default true,
  last_seen_cycle_id uuid references public.devir_sync_cycles(id) on delete set null,
  last_seen_at timestamptz not null default now(),
  last_synced_at timestamptz,
  last_error text,
  updated_at timestamptz not null default now()
);

create index if not exists devir_sync_catalog_cycle_idx
  on public.devir_sync_catalog(last_seen_cycle_id);

